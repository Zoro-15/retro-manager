const char* kFontVertexShader =
    "attribute vec2 aPosition;\n"
    "attribute vec2 aTexCoord;\n"
    "uniform vec2 uScreenSize;\n"
    "varying vec2 vTexCoord;\n"
    "void main() {\n"
    "    vec2 zeroToOne = aPosition / uScreenSize;\n"
    "    vec2 zeroToTwo = zeroToOne * 2.0;\n"
    "    vec2 clipSpace = zeroToTwo - 1.0;\n"
    "    gl_Position = vec4(clipSpace.x, -clipSpace.y, 0.0, 1.0);\n"
    "    vTexCoord = aTexCoord;\n"
    "}\n";

const char* kFontFragmentShader =
    "precision mediump float;\n"
    "varying vec2 vTexCoord;\n"
    "uniform vec4 uColor;\n"
    "uniform sampler2D uSampler;\n"
    "void main() {\n"
    "    float alpha = texture2D(uSampler, vTexCoord).a;\n"
    "    gl_FragColor = vec4(uColor.rgb, uColor.a * alpha);\n"
    "}\n";

// Texture layout: 16 columns x 8 rows = 128 chars
// Each char is 8x8 pixels => Texture size = 128 x 64 pixels
constexpr int ATLAS_COLS = 16;
constexpr int ATLAS_ROWS = 8;
constexpr int CHAR_PIXELS = 8;
constexpr int ATLAS_WIDTH = ATLAS_COLS * CHAR_PIXELS;  // 128
constexpr int ATLAS_HEIGHT = ATLAS_ROWS * CHAR_PIXELS; // 64

