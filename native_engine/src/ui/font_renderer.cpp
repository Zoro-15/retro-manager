FontRenderer& FontRenderer::instance() {
    static FontRenderer s_instance;
    return s_instance;
}

FontRenderer::FontRenderer() = default;

FontRenderer::~FontRenderer() {
    terminateGL();
}

bool FontRenderer::initGL() {
    if (m_initialized) return true;

    // 1. Build Font Atlas Bitmap (128x64 Alpha texture)
    std::vector<uint8_t> atlasData(ATLAS_WIDTH * ATLAS_HEIGHT, 0);

    for (int charIdx = 0; charIdx < 95; ++charIdx) {
        int col = charIdx % ATLAS_COLS;
        int row = charIdx / ATLAS_COLS;

        int startX = col * CHAR_PIXELS;
        int startY = row * CHAR_PIXELS;

        for (int py = 0; py < 8; ++py) {
            uint8_t rowBits = kFont8x8[charIdx][py];
            for (int px = 0; px < 8; ++px) {
                bool set = (rowBits & (0x80 >> px)) != 0;
                int atlasIdx = (startY + py) * ATLAS_WIDTH + (startX + px);
                atlasData[atlasIdx] = set ? 255 : 0;
            }
        }
    }

    // 2. Upload Texture to OpenGL
    glGenTextures(1, &m_textureId);
    glBindTexture(GL_TEXTURE_2D, m_textureId);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, GL_NEAREST);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MAG_FILTER, GL_NEAREST);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_S, GL_CLAMP_TO_EDGE);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_T, GL_CLAMP_TO_EDGE);

    glPixelStorei(GL_UNPACK_ALIGNMENT, 1);
    glTexImage2D(GL_TEXTURE_2D, 0, GL_ALPHA, ATLAS_WIDTH, ATLAS_HEIGHT, 0, GL_ALPHA, GL_UNSIGNED_BYTE, atlasData.data());

    // 3. Compile Shaders
    GLuint vs = glCreateShader(GL_VERTEX_SHADER);
    glShaderSource(vs, 1, &kFontVertexShader, nullptr);
    glCompileShader(vs);

    GLuint fs = glCreateShader(GL_FRAGMENT_SHADER);
    glShaderSource(fs, 1, &kFontFragmentShader, nullptr);
    glCompileShader(fs);

    m_program = glCreateProgram();
    glAttachShader(m_program, vs);
    glAttachShader(m_program, fs);
    glLinkProgram(m_program);

    glDeleteShader(vs);
    glDeleteShader(fs);

    m_locPosition = glGetAttribLocation(m_program, "aPosition");
    m_locTexCoord = glGetAttribLocation(m_program, "aTexCoord");
    m_locColor = glGetUniformLocation(m_program, "uColor");
    m_locScreenSize = glGetUniformLocation(m_program, "uScreenSize");
    m_locSampler = glGetUniformLocation(m_program, "uSampler");

    m_initialized = (m_program != 0 && m_textureId != 0);
    LOGI("FontRenderer initialized (GL texture: %u, program: %u)", m_textureId, m_program);
    return m_initialized;
}

void FontRenderer::terminateGL() {
    if (m_textureId != 0) {
        glDeleteTextures(1, &m_textureId);
        m_textureId = 0;
    }
    if (m_program != 0) {
        glDeleteProgram(m_program);
        m_program = 0;
    }
    m_initialized = false;
}

float FontRenderer::getTextWidth(const std::string& text, float scale) const {
    return static_cast<float>(text.length()) * 8.0f * scale;
}

float FontRenderer::getTextHeight(float scale) const {
    return 8.0f * scale;
}

void FontRenderer::renderText(
    const std::string& text,
    float x,
    float y,
    float scale,
    float r,
    float g,
    float b,
    float a,
    int screenW,
    int screenH,
    bool centerX,
    bool centerY
) {
    if (text.empty() || a <= 0.0f || screenW <= 0 || screenH <= 0) return;
    if (!initGL()) return;

    float totalW = getTextWidth(text, scale);
    float totalH = getTextHeight(scale);

    float startX = centerX ? (x - totalW * 0.5f) : x;
    float startY = centerY ? (y - totalH * 0.5f) : y;

    glUseProgram(m_program);
    glUniform2f(m_locScreenSize, static_cast<float>(screenW), static_cast<float>(screenH));

    glActiveTexture(GL_TEXTURE0);
    glBindTexture(GL_TEXTURE_2D, m_textureId);
    glUniform1i(m_locSampler, 0);

    glEnable(GL_BLEND);
    glBlendFunc(GL_SRC_ALPHA, GL_ONE_MINUS_SRC_ALPHA);

    // Build geometry for all characters
    std::vector<GLfloat> vertexData;
    vertexData.reserve(text.length() * 6 * 4); // 6 vertices per quad, 4 floats (pos: 2, uv: 2)

    float curX = startX;
    float charW = 8.0f * scale;
    float charH = 8.0f * scale;

    float invAtlasW = 1.0f / static_cast<float>(ATLAS_WIDTH);
    float invAtlasH = 1.0f / static_cast<float>(ATLAS_HEIGHT);

    for (char c : text) {
        int ascii = static_cast<unsigned char>(c);
        if (ascii < 32 || ascii > 126) {
            ascii = 32; // Space for unsupported chars
        }
        int charIdx = ascii - 32;

        int col = charIdx % ATLAS_COLS;
        int row = charIdx / ATLAS_COLS;

        float u0 = (col * CHAR_PIXELS) * invAtlasW;
        float v0 = (row * CHAR_PIXELS) * invAtlasH;
        float u1 = (col * CHAR_PIXELS + CHAR_PIXELS) * invAtlasW;
        float v1 = (row * CHAR_PIXELS + CHAR_PIXELS) * invAtlasH;

        float x0 = curX;
        float y0 = startY;
        float x1 = curX + charW;
        float y1 = startY + charH;

        // Quad 1: (x0, y0), (x0, y1), (x1, y0)
        vertexData.push_back(x0); vertexData.push_back(y0); vertexData.push_back(u0); vertexData.push_back(v0);
        vertexData.push_back(x0); vertexData.push_back(y1); vertexData.push_back(u0); vertexData.push_back(v1);
        vertexData.push_back(x1); vertexData.push_back(y0); vertexData.push_back(u1); vertexData.push_back(v0);

        // Quad 2: (x1, y0), (x0, y1), (x1, y1)
        vertexData.push_back(x1); vertexData.push_back(y0); vertexData.push_back(u1); vertexData.push_back(v0);
        vertexData.push_back(x0); vertexData.push_back(y1); vertexData.push_back(u0); vertexData.push_back(v1);
        vertexData.push_back(x1); vertexData.push_back(y1); vertexData.push_back(u1); vertexData.push_back(v1);

        curX += charW;
    }

    // Set vertex attributes
    glVertexAttribPointer(m_locPosition, 2, GL_FLOAT, GL_FALSE, 4 * sizeof(GLfloat), vertexData.data());
    glEnableVertexAttribArray(m_locPosition);

    glVertexAttribPointer(m_locTexCoord, 2, GL_FLOAT, GL_FALSE, 4 * sizeof(GLfloat), vertexData.data() + 2);
    glEnableVertexAttribArray(m_locTexCoord);

    // 1. Draw Subtle Dark Drop Shadow for razor-sharp readability on any background
    glUniform4f(m_locColor, 0.0f, 0.0f, 0.0f, a * 0.75f);
    // Offset position by +1.5px
    for (size_t i = 0; i < vertexData.size(); i += 4) {
        vertexData[i] += 1.5f;
        vertexData[i + 1] += 1.5f;
    }
    glVertexAttribPointer(m_locPosition, 2, GL_FLOAT, GL_FALSE, 4 * sizeof(GLfloat), vertexData.data());
    glDrawArrays(GL_TRIANGLES, 0, static_cast<GLsizei>(text.length() * 6));

    // Restore positions
    for (size_t i = 0; i < vertexData.size(); i += 4) {
        vertexData[i] -= 1.5f;
        vertexData[i + 1] -= 1.5f;
    }
    glVertexAttribPointer(m_locPosition, 2, GL_FLOAT, GL_FALSE, 4 * sizeof(GLfloat), vertexData.data());

    // 2. Draw Foreground Text
    glUniform4f(m_locColor, r, g, b, a);
    glDrawArrays(GL_TRIANGLES, 0, static_cast<GLsizei>(text.length() * 6));

    glDisableVertexAttribArray(m_locPosition);
    glDisableVertexAttribArray(m_locTexCoord);
}

